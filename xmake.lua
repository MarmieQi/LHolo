-- The JSON files are the only translation sources. xmake scans this directory
-- on every project load and writes transient resource/registry files under
-- build/; adding a new locale JSON therefore registers it on the next build
-- without a Python script or a checked-in generated file.
rule("lholo.i18n.resources")
    on_load(function(target)
        local language_files = os.files("src/i18n/lang/*.json")
        if #language_files == 0 then
            raise("no language JSON files found in src/i18n/lang")
        end
        table.sort(language_files)
        local has_default_language = false

        local manifest_dir = path.join(os.projectdir(), "build", "generated", "i18n")
        local manifest = path.join(manifest_dir, "Languages.rc")
        local registry = path.join(manifest_dir, "LanguageRegistry.generated.h")
        local lines = {
            "// GENERATED by xmake.lua; do not edit.",
            "#pragma code_page(65001)",
            ""
        }
        local registry_lines = {
            "// GENERATED by xmake.lua; do not edit.",
            "#pragma once",
            "",
            "#include <array>",
            "#include <string_view>",
            "",
            "namespace lholo::i18n::generated {",
            "",
            "struct LanguageResource {",
            "    std::string_view code;",
            "    wchar_t const* resourceName;",
            "};",
            "",
            "inline constexpr std::array<LanguageResource, " .. #language_files .. "> kLanguageResources{{"
        }
        local identifiers = {}
        for _, language_file in ipairs(language_files) do
            local language_code = path.basename(language_file)
            if not language_code:match("^[%a][%w]*_[%a][%w]*$") then
                raise("invalid language filename (expected xx_YY.json): " .. language_file)
            end
            if language_code == "zh_CN" then
                has_default_language = true
            end

            local resource_code = language_code:upper():gsub("[^%w]", "_")
            local identifier = "LHOLO_LANG_" .. resource_code
            if identifiers[identifier] then
                raise("language resource ID collision: " .. identifier)
            end
            identifiers[identifier] = true

            local absolute_path = path.unix(path.absolute(language_file))
            table.insert(lines, identifier .. " RCDATA \"" .. absolute_path .. "\"")
            table.insert(
                registry_lines,
                "    {\"" .. language_code .. "\", L\"" .. identifier .. "\"},"
            )
        end
        if not has_default_language then
            raise("default language file is missing: src/i18n/lang/zh_CN.json")
        end
        table.insert(lines, "")
        table.insert(registry_lines, "}};")
        table.insert(registry_lines, "")
        table.insert(registry_lines, "} // namespace lholo::i18n::generated")

        local content = table.concat(lines, "\n")
        local escaped_manifest = path.unix(path.absolute(manifest)):gsub("'", "''")
        local escaped_registry = path.unix(path.absolute(registry)):gsub("'", "''")
        local registry_content = table.concat(registry_lines, "\n")
        local powershell = "$manifest = '" .. escaped_manifest .. "'\n"
            .. "$registry = '" .. escaped_registry .. "'\n"
            .. "$content = @'\n" .. content .. "\n'@\n"
            .. "$registryContent = @'\n" .. registry_content .. "\n'@\n"
            .. "$directory = Split-Path -Parent $manifest\n"
            .. "New-Item -ItemType Directory -Force -Path $directory | Out-Null\n"
            .. "[System.IO.File]::WriteAllText($manifest, $content, [System.Text.UTF8Encoding]::new($false))\n"
            .. "[System.IO.File]::WriteAllText($registry, $registryContent, [System.Text.UTF8Encoding]::new($false))\n"
        os.vrunv("powershell", {"-NoProfile", "-NonInteractive", "-Command", powershell})
        target:add("files", manifest)
    end)
rule_end()

